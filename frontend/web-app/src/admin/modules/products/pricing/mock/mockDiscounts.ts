export function getActiveDiscounts(): DiscountRule[] {
  return MOCK_DISCOUNT_RULES.filter((d) => d.status === 'active');
}

export function getDiscountsForEntity(entityId: string, categoryId?: string, brandId?: string): DiscountRule[] {
  return MOCK_DISCOUNT_RULES.filter(
    (d) =>
      d.status === 'active' &&
      (d.applicableTo === 'all' ||
        d.applicableIds.includes(entityId) ||
        (categoryId && d.applicableIds.includes(categoryId)) ||
        (brandId && d.applicableIds.includes(brandId)))
  );
}
